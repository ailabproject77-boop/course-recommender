COLUMNS = ["course_id", "name", "category", "level", "difficulty",
           "prerequisites", "skills", "description"]


def generate(seed=42, n_students=300):
    """Return (courses, students, ratings) DataFrames."""
    rng = np.random.default_rng(seed)
    courses = pd.DataFrame(COURSES, columns=COLUMNS)

    popularity = rng.uniform(0.6, 1.4, len(courses))          # some courses are more popular
    info = {}
    for i, r in enumerate(courses.itertuples()):
        info[r.course_id] = dict(
            cat=r.category, level=r.level, diff=r.difficulty, pop=popularity[i],
            prereq=[p for p in r.prerequisites.split(";") if p],
            skills=set(r.skills.split(";")),
        )
    all_skills = sorted(set().union(*[v["skills"] for v in info.values()]))
    cat_skills = {c: sorted(set().union(*[v["skills"] for v in info.values() if v["cat"] == c]))
                  for c in INTERESTS}

    students, rows = [], []
    for n in range(n_students):
        sid = f"S{n + 1:03d}"
        k = int(rng.choice([1, 2, 3], p=[0.3, 0.5, 0.2]))
        interests = [str(x) for x in rng.choice(INTERESTS, size=k, replace=False)]
        pool = sorted(set().union(*[cat_skills[c] for c in interests]))
        skills = set()
        for _ in range(int(rng.integers(3, 7))):              # 3-6 skills, mostly related to interests
            src = pool if rng.random() < 0.75 else all_skills
            skills.add(str(rng.choice(src)))
        semester = int(rng.integers(3, 9))                    # semester they are choosing for (3..8)
        pref = int(rng.choice([2, 3, 4], p=[0.25, 0.5, 0.25]))  # preferred difficulty
        students.append(dict(student_id=sid, interests=";".join(interests),
                             skills=";".join(sorted(skills)), semester=semester,
                             preferred_difficulty=pref))

        done = set()
        for t in range(1, semester + 1):                      # simulate every semester up to `semester`
            elig = [c for c, v in info.items()
                    if c not in done and all(p in done for p in v["prereq"])
                    and t - 2 <= v["level"] <= t + 1]
            if not elig:
                continue
            w = []
            for c in elig:
                v = info[c]
                overlap = len(v["skills"] & skills)
                w.append((1 + 3 * (v["cat"] in interests)) * (1 + 0.4 * overlap) * v["pop"]
                         * np.exp(-0.6 * abs(v["level"] - t))
                         * np.exp(-0.25 * abs(v["diff"] - pref)))
            w = np.array(w) / np.sum(w)
            n_take = min(3 if t == 1 else 5, len(elig))
            chosen = rng.choice(len(elig), size=n_take, replace=False, p=w)
            for j in chosen:
                c = elig[j]
                v = info[c]
                frac = len(v["skills"] & skills) / len(v["skills"])
                base = (3.0 + 1.0 * (v["cat"] in interests) + 0.6 * frac
                        - 0.3 * abs(v["diff"] - pref))
                rating = int(np.clip(round(base + rng.normal(0, 0.6)), 1, 5))
                rows.append(dict(student_id=sid, course_id=c, rating=rating, semester_taken=t))
            done |= {elig[j] for j in chosen}                 # unlocked only from next semester

    return courses, pd.DataFrame(students), pd.DataFrame(rows)


def save(out_dir="data", seed=42):
    out = Path(out_dir)
    out.mkdir(exist_ok=True)
    courses, students, ratings = generate(seed)
    courses.to_csv(out / "courses.csv", index=False)
    students.to_csv(out / "students.csv", index=False)
    ratings.to_csv(out / "ratings.csv", index=False)
    return courses, students, ratings


